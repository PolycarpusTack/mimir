#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_html_has_header() {
        let html = render_digest_html("## Test Section\nSome content.", "2026-W13");
        assert!(html.contains("AirPulse Intelligence Digest"));
        assert!(html.contains("class=\"header\""));
        assert!(html.contains("#F59E0B")); // amber color
        assert!(html.contains("2026-W13"));
    }

    #[test]
    fn test_html_has_footer() {
        let html = render_digest_html("Content here.", "2026-W13");
        assert!(html.contains("class=\"footer\""));
        assert!(html.contains("Mediagenix"));
        assert!(html.contains("mediagenix.tv"));
        assert!(html.contains("Do not reply"));
    }

    #[test]
    fn test_html_contains_content() {
        let html = render_digest_html("Important signal about AWS.", "2026-W13");
        assert!(html.contains("Important signal about AWS."));
    }

    #[test]
    fn test_html_escapes_special_chars() {
        let html = render_digest_html("Revenue > $1B & growing <fast>.", "2026-W13");
        assert!(html.contains("&amp;"));
        assert!(html.contains("&lt;fast&gt;"));
    }

    #[test]
    fn test_html_renders_headers() {
        let html = render_digest_html("## Shift Signals\n### AI Trends", "2026-W13");
        assert!(html.contains("<h2>"));
        assert!(html.contains("<h3>"));
    }

    #[test]
    fn test_html_renders_list() {
        let html = render_digest_html("- Item one\n- Item two", "2026-W13");
        assert!(html.contains("<ul>"));
        assert!(html.contains("<li>"));
        assert!(html.contains("</ul>"));
    }
}
