/// Simple markdown-to-HTML converter for digest content.
/// Handles headers (##, ###), bold (**), italic (*), bullet lists, and paragraphs.
fn markdown_to_html(markdown: &str) -> String {
    let mut html = String::new();
    let mut in_list = false;

    for line in markdown.lines() {
        let trimmed = line.trim();

        if trimmed.is_empty() {
            if in_list {
                html.push_str("</ul>\n");
                in_list = false;
            }
            continue;
        }

        // Headers
        if let Some(rest) = trimmed.strip_prefix("### ") {
            if in_list {
                html.push_str("</ul>\n");
                in_list = false;
            }
            html.push_str(&format!("<h3>{}</h3>\n", escape_html(rest)));
        } else if let Some(rest) = trimmed.strip_prefix("## ") {
            if in_list {
                html.push_str("</ul>\n");
                in_list = false;
            }
            html.push_str(&format!("<h2>{}</h2>\n", escape_html(rest)));
        } else if let Some(rest) = trimmed.strip_prefix("# ") {
            if in_list {
                html.push_str("</ul>\n");
                in_list = false;
            }
            html.push_str(&format!("<h1>{}</h1>\n", escape_html(rest)));
        }
        // Bullet list items
        else if let Some(rest) = trimmed.strip_prefix("- ").or_else(|| trimmed.strip_prefix("* "))
        {
            if !in_list {
                html.push_str("<ul>\n");
                in_list = true;
            }
            html.push_str(&format!("<li>{}</li>\n", inline_format(rest)));
        }
        // Regular paragraph
        else {
            if in_list {
                html.push_str("</ul>\n");
                in_list = false;
            }
            html.push_str(&format!("<p>{}</p>\n", inline_format(trimmed)));
        }
    }

    if in_list {
        html.push_str("</ul>\n");
    }

    html
}

/// Apply inline formatting: **bold** and *italic*.
fn inline_format(text: &str) -> String {
    let escaped = escape_html(text);

    // Simple bold replacement: pairs of ** become <strong>...</strong>
    let mut result = String::new();
    let mut in_bold = false;
    let parts: Vec<&str> = escaped.split("**").collect();
    for (i, part) in parts.iter().enumerate() {
        result.push_str(part);
        if i < parts.len() - 1 {
            if in_bold {
                result.push_str("</strong>");
            } else {
                result.push_str("<strong>");
            }
            in_bold = !in_bold;
        }
    }

    result
}

/// Escape HTML special characters.
fn escape_html(text: &str) -> String {
    text.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

// ---------------------------------------------------------------------------
// Tests
